#!/usr/bin/env node
// Runs the verification suite and writes TEST_RESULTS.md from what actually happened.
//
//   node scripts/record_test_results.mjs             # tests + sanitizers + all gates
//   node scripts/record_test_results.mjs --no-gates  # tests and sanitizers only
//
// The document is generated rather than written by hand, so a pass rate in it is a
// transcript of a run and not a recollection of one.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, run, runGtest, ensureBuild, cpuCount } from './gates/_lib.mjs';

const skipGates = process.argv.includes('--no-gates');
const started = new Date();
const lines = [];
const w = (s = '') => lines.push(s);

const env = {
  os: run('uname', ['-srm']).out.trim(),
  cpu: run('sh', ['-c', 'sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown']).out.trim(),
  cores: run('sh', ['-c', 'sysctl -n hw.ncpu 2>/dev/null || nproc']).out.trim(),
  compiler: run('sh', ['-c', 'c++ --version | head -1']).out.trim(),
  cmake: run('sh', ['-c', 'cmake --version | head -1']).out.trim(),
  sqlite: run('sh', ['-c', 'sqlite3 --version 2>/dev/null | cut -d" " -f1']).out.trim(),
};

console.log('building...');
ensureBuild('build');

// ---- suite breakdown, read from the runner --------------------------------------------
console.log('running the test suite...');
const listed = runGtest('*', path.join(ROOT, 'build'), {}, ['--gtest_list_tests']);
const perSuite = new Map();
let currentSuite = null;
for (const line of listed.out.split('\n')) {
  if (/^\S+\.\s*$/.test(line.trim()) && !line.startsWith(' ')) {
    currentSuite = line.trim().replace(/\.$/, '');
    perSuite.set(currentSuite, 0);
  } else if (currentSuite && /^\s{2}\S/.test(line)) {
    perSuite.set(currentSuite, perSuite.get(currentSuite) + 1);
  }
}

const release = runGtest('*', path.join(ROOT, 'build'));
console.log(`  ${release.passed}/${release.total} passed`);

// ---- sanitizers --------------------------------------------------------------------------
function sanitizerRun(name, dir, sanitizer, env2) {
  const buildDir = path.join(ROOT, dir);
  if (!fs.existsSync(path.join(buildDir, 'CMakeCache.txt'))) {
    run('cmake', ['-S', ROOT, '-B', buildDir, '-DCMAKE_BUILD_TYPE=Debug',
                  `-DJOBENGINE_SANITIZER=${sanitizer}`, '-DJOBENGINE_BUILD_TESTS=ON']);
  }
  const build = run('cmake', ['--build', buildDir, '-j', String(cpuCount())], { timeout: 1800000 });
  if (build.code !== 0) return { available: false, reason: build.out.slice(-400) };
  const r = runGtest('*', buildDir, env2);
  return {
    available: true,
    total: r.total, passed: r.passed, failed: r.failed, code: r.code,
    tsanWarnings: (r.out.match(/WARNING: ThreadSanitizer/g) || []).length,
    asanErrors: (r.out.match(/ERROR: AddressSanitizer/g) || []).length,
    ubsanErrors: (r.out.match(/runtime error:/g) || []).length,
  };
}

console.log('running under ThreadSanitizer...');
const tsan = sanitizerRun('tsan', 'build-tsan', 'thread', { TSAN_OPTIONS: 'halt_on_error=0' });
console.log('running under AddressSanitizer + UBSan...');
const asan = sanitizerRun('asan', 'build-asan', 'address',
                          { ASAN_OPTIONS: 'halt_on_error=0', UBSAN_OPTIONS: 'print_stacktrace=1' });

// ---- leak check ----------------------------------------------------------------------------
let leakLine = 'not run';
if (run('sh', ['-c', 'command -v leaks >/dev/null && echo yes || echo no']).out.trim() === 'yes') {
  console.log('running the platform leak checker...');
  const lr = run('sh', ['-c',
    `MallocStackLogging=1 leaks --atExit -- ${path.join(ROOT, 'build', 'jobengine_tests')} ` +
    `--gtest_brief=1 2>&1 | tail -5`], { timeout: 1800000 });
  const m = /(\d+) leaks for (\d+) total leaked bytes/.exec(lr.out);
  leakLine = m ? `${m[1]} leaks, ${m[2]} bytes` : `no verdict: ${lr.out.trim().slice(-200)}`;
}

// ---- gates ------------------------------------------------------------------------------------
const gateResults = [];
if (!skipGates) {
  const gateDir = path.join(ROOT, 'scripts', 'gates');
  const gates = fs.readdirSync(gateDir).filter((f) => /^g\d+_.*\.mjs$/.test(f)).sort();
  for (const g of gates) {
    process.stdout.write(`running ${g} ... `);
    const r = run('node', [path.join(gateDir, g)], { timeout: 2400000 });
    const id = /GATE (G\d+) PASS/.exec(r.out);
    const passed = r.code === 0 && id !== null;
    const summary = r.out.split('\n').filter((l) => l.trim() && !/^GATE /.test(l));
    gateResults.push({ name: g, passed, summary, failure: passed ? '' : r.out.slice(-1200) });
    console.log(passed ? 'PASS' : 'FAIL');
  }
}

// ---- document -----------------------------------------------------------------------------------
const finished = new Date();
w('# TEST RESULTS');
w('');
w('Generated by `node scripts/record_test_results.mjs`. Everything below is a transcript of');
w('an actual run, not a summary written from memory. Re-run the command to regenerate it.');
w('');
w(`- **Run started:** ${started.toISOString()}`);
w(`- **Run finished:** ${finished.toISOString()}`);
w(`- **Duration:** ${((finished - started) / 1000).toFixed(0)}s`);
w('');
w('## Environment');
w('');
w('| | |');
w('|---|---|');
w(`| OS | ${env.os} |`);
w(`| CPU | ${env.cpu} (${env.cores} logical cores) |`);
w(`| Compiler | ${env.compiler} |`);
w(`| CMake | ${env.cmake} |`);
w(`| SQLite | ${env.sqlite} |`);
w('');
w('## Test suite (Release build)');
w('');
w(`**${release.passed} of ${release.total} tests passed** across ${release.suites} suites ` +
  `(${release.failed} failed). Counts are parsed from the GoogleTest runner's own output.`);
w('');
w('| Suite | Tests |');
w('|---|---|');
for (const [suite, n] of [...perSuite.entries()].sort()) w(`| \`${suite}\` | ${n} |`);
w(`| **total** | **${[...perSuite.values()].reduce((a, b) => a + b, 0)}** |`);
w('');
w('## Sanitizers');
w('');
w('| Run | Tests | Passed | Findings |');
w('|---|---|---|---|');
w(`| ThreadSanitizer | ${tsan.available ? tsan.total : '-'} | ${tsan.available ? tsan.passed : '-'} | ` +
  `${tsan.available ? `${tsan.tsanWarnings} data race warning(s)` : 'build failed'} |`);
w(`| AddressSanitizer + UBSan | ${asan.available ? asan.total : '-'} | ${asan.available ? asan.passed : '-'} | ` +
  `${asan.available ? `${asan.asanErrors} ASan error(s), ${asan.ubsanErrors} UBSan error(s)` : 'build failed'} |`);
w(`| Leak check (platform \`leaks\`) | - | - | ${leakLine} |`);
w('');
w('LeakSanitizer is not supported on macOS/arm64, so leak coverage comes from the platform');
w('`leaks` tool run against the ordinary Release binary.');
w('');
if (!skipGates) {
  const passedGates = gateResults.filter((g) => g.passed).length;
  w('## Acceptance gates');
  w('');
  w(`**${passedGates} of ${gateResults.length} gates passed.** Each gate verifies one claim`);
  w('end to end and prints its own measured summary.');
  w('');
  for (const g of gateResults) {
    w(`### \`${g.name}\` - ${g.passed ? 'PASS' : 'FAIL'}`);
    w('');
    w('```');
    for (const line of (g.passed ? g.summary : g.failure.split('\n')).slice(0, 24)) w(line);
    w('```');
    w('');
  }
}
w('## How to reproduce');
w('');
w('```bash');
w('cmake -S . -B build -DCMAKE_BUILD_TYPE=Release && cmake --build build -j');
w('./build/jobengine_tests');
w('node scripts/record_test_results.mjs      # regenerates this document');
w('```');
w('');

fs.writeFileSync(path.join(ROOT, 'TEST_RESULTS.md'), lines.join('\n'));
console.log(`\nwrote TEST_RESULTS.md`);
const gatesFailed = gateResults.filter((g) => !g.passed);
if (release.failed > 0 || gatesFailed.length > 0) {
  console.error(`FAILURES: ${release.failed} test(s), ${gatesFailed.length} gate(s)`);
  process.exit(1);
}
